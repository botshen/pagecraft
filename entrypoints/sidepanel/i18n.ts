interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

export const I18nContext = createContext<I18nCtx>({
  lang: 'zh',
  setLang: () => {},
  t: (k) => k,
});

export function useI18nProvider(): I18nCtx {
  const [lang, setLangState] = useState<Lang>(detectBrowserLang);

  useEffect(() => {
    try {
      const q = new URLSearchParams(window.location.search).get('lang');
      if (q === 'zh' || q === 'en') return;
      chrome.storage?.local?.remove?.('pc_lang');
      chrome.storage?.local?.get?.(MANUAL_LANG_STORAGE_KEY, (res) => {
        const manual = res?.[MANUAL_LANG_STORAGE_KEY];
        if (manual === 'zh' || manual === 'en') {
          setLangState(manual);
        }
      });
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    saveManualLangOverride(next);
  }, []);

  const t = useCallback((key: string) => STRINGS[lang][key] ?? key, [lang]);

  return { lang, setLang, t };
}

export function useI18n() {
  return useContext(I18nContext);
}
